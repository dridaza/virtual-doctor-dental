// Within each tooth's full band, the crown sits on the side closest to the
// tooth-number label and the root tapers away from it. Upper rows (18-28,
// 55-65) print the number below the icon, so the crown is the bottom half;
// lower rows (85-75, 48-38) print the number above the icon, so the crown is
// the top half.
const CROWN_NEAR_BOTTOM = new Set([
  '18', '17', '16', '15', '14', '13', '12', '11', '21', '22', '23', '24', '25', '26', '27', '28',
  '55', '54', '53', '52', '51', '61', '62', '63', '64', '65',
]);

// 10 background lines behind the root, spanning a 10mm probing-depth scale (one line every 1mm).
export const PERIODONTOGRAMA_LINE_COUNT = 10;
export const PERIODONTOGRAMA_MM_SPAN = 10;

export function getCrownRootRects(tooth: string): { corona: ToothPosition; raiz: ToothPosition } {
  const band = TOOTH_POSITIONS[tooth];
  const half = band.hPct / 2;
  const crownNearBottom = CROWN_NEAR_BOTTOM.has(tooth);
  const top: ToothPosition = { xPct: band.xPct, yPct: band.yPct, wPct: band.wPct, hPct: half };
  const bottom: ToothPosition = { xPct: band.xPct, yPct: band.yPct + half, wPct: band.wPct, hPct: half };
  return crownNearBottom ? { corona: bottom, raiz: top } : { corona: top, raiz: bottom };
}

export function formatToothFinding(rawCode: string): string {
  const tokens = rawCode.split(',').map((t) => t.trim()).filter(Boolean);
  return tokens
    .map((token) => {
      const ref = ODONTOGRAMA_REFERENCIAS.find((r) => r.code.toLowerCase() === token.toLowerCase());
      return ref ? `${ref.code} (${ref.label})` : token;
    })
    .join(', ');
}

export function buildOdontogramaSummary(
  corona: Record<string, string>,
  raiz: Record<string, string> = {}
): string {
  const teeth = new Set([...Object.keys(corona), ...Object.keys(raiz)]);
  const entries = Array.from(teeth).filter((t) => (corona[t] && corona[t].trim()) || (raiz[t] && raiz[t].trim()));
  if (entries.length === 0) return '';
  const intro = 'Se realizó el estudio físico oral según la NOM-004-SSA3-2012 y se encontró:';
  const body = entries
    .sort((a, b) => a.localeCompare(b))
    .map((tooth) => {
      const parts: string[] = [];
      if (corona[tooth]?.trim()) parts.push(formatToothFinding(corona[tooth]));
      if (raiz[tooth]?.trim()) parts.push(`profundidad de sondaje ${raiz[tooth]}mm`);
      return `Pieza ${tooth}: ${parts.join('; ')}`;
    })
    .join('. ');
  return `${intro} ${body}.`;
}

